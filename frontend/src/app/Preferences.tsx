export type TranslationKey = keyof typeof messages.vi;
type Locale = keyof typeof messages;
type Theme = 'light' | 'dark';
type Preferences = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  theme: Theme;
  setTheme: (theme: Theme) => void;
  showCursors: boolean;
  setShowCursors: (show: boolean) => void;
  t: (key: TranslationKey) => string;
};

const PreferencesContext = createContext<Preferences | null>(null);

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => localStorage.getItem('collabcanvas.locale') === 'en' ? 'en' : 'vi');
  const [theme, setTheme] = useState<Theme>(() => {
    const saved = localStorage.getItem('collabcanvas.theme');
    return saved === 'light' || saved === 'dark' ? saved : 'dark';
  });
  const [showCursors, setShowCursors] = useState(() => localStorage.getItem('collabcanvas.showCursors') !== 'false');

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    localStorage.setItem('collabcanvas.theme', theme);
  }, [theme]);

  useEffect(() => {
    document.documentElement.lang = locale;
    localStorage.setItem('collabcanvas.locale', locale);
  }, [locale]);

  useEffect(() => {
    localStorage.setItem('collabcanvas.showCursors', String(showCursors));
  }, [showCursors]);

  const value = useMemo(() => ({
    locale, setLocale, theme, setTheme, showCursors, setShowCursors,
    t: (key: TranslationKey) => messages[locale][key],
  }), [locale, theme, showCursors]);
  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error('PreferencesProvider is missing');
  return context;
}
